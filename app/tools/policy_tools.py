#: Low-signal English tokens removed from the direct-term list.
_STOPWORDS = {
    "the", "a", "an", "and", "or", "of", "to", "for", "in", "on", "at", "is",
    "are", "was", "were", "be", "been", "can", "could", "do", "does", "did",
    "how", "what", "when", "where", "which", "who", "why", "with", "my", "me",
    "i", "we", "you", "your", "our", "it", "this", "that", "there", "if",
    "about", "from", "by", "as", "any", "all", "not", "but", "have", "has",
    "had", "should", "would", "will", "shall", "may", "much", "many", "get",
    "please", "tell", "want", "need", "know",
}

_ASCII_TOKEN_RE = re.compile(r"[A-Za-z][A-Za-z0-9'\-]*|\d+(?:[.,]\d+)*")
_SECTION_REF_RE = re.compile(r"\b(\d+\.\d+)\b")


def _build_query_terms(query: str) -> list[tuple[str, float]]:
    """Expand `query` into weighted lowercase search terms (deterministic)."""
    q = normalize_policy_text(query).lower()
    terms: dict[str, float] = {}

    def add(term: str, weight: float) -> None:
        term = term.strip().lower()
        if not term or term in _STOPWORDS:
            return
        if len(term) < 2 and not term.isdigit():
            return
        terms[term] = max(terms.get(term, 0.0), weight)

    # 1. Direct ASCII tokens straight from the question (highest confidence).
    for tok in _ASCII_TOKEN_RE.findall(q):
        add(tok, 1.0)

    # 2. Synonym expansion driven by substring triggers (handles Japanese,
    #    which has no whitespace tokenisation).
    for trigger, expansions in _SYNONYMS.items():
        if trigger in q:
            for exp in expansions:
                add(exp, 0.85)

    return sorted(terms.items(), key=lambda kv: (-kv[1], kv[0]))


def _count_exact(haystack: str, term: str) -> int:
    return len(re.findall(r"(?<![a-z0-9])" + re.escape(term) + r"(?![a-z0-9])", haystack))


def _score_section(
    section: dict[str, Any], terms: list[tuple[str, float]], raw_query: str
) -> float:
    """Deterministic keyword score: exact term > heading hit > partial body hit."""
    title_hay = section["_haystack_title"]
    body_hay = section["_haystack_body"]
    score = 0.0

    for term, weight in terms:
        matched_title = False
        if _count_exact(title_hay, term):
            score += 8.0 * weight
            matched_title = True
        elif term in title_hay:
            score += 4.0 * weight
            matched_title = True

        exact_body = _count_exact(body_hay, term)
        if exact_body:
            score += min(exact_body, 4) * (3.0 if " " in term else 2.5) * weight
        elif term in body_hay:
            score += min(body_hay.count(term), 4) * 0.75 * weight
        elif not matched_title and " " in term:
            # Multi-word synonym: give partial credit when every word is present.
            words = term.split()
            if all(_count_exact(body_hay, w) for w in words):
                score += 1.5 * weight

    # Whole-question phrase match (English queries).
    q_norm = _searchable(raw_query).strip()
    if len(q_norm) > 8 and q_norm in body_hay:
        score += 12.0

    # Explicit section references ("5.4", "Section 25.3").
    for ref in _SECTION_REF_RE.findall(raw_query):
        if ref == section["number"]:
            score += 30.0
        elif section["number"].startswith(ref.split(".")[0] + "."):
            score += 2.0

    return score


#: Minimum score required before a section is considered a genuine hit.
_SCORE_THRESHOLD = 3.0
_MAX_RESULTS = 5
_MAX_CONTENT_CHARS = 3000


def _section_sort_key(section: dict[str, Any]) -> tuple[int, int]:
    major, _, minor = section["number"].partition(".")
    return (int(major), int(minor) if minor else 0)


def _as_result(section: dict[str, Any], score: float | None = None) -> dict[str, Any]:
    """Project an internal section record onto the stable public result shape."""
    result: dict[str, Any] = {
        "section_id": section["section_id"],
        "title": section["title"],
        "content": section["content"][:_MAX_CONTENT_CHARS],
        "citation_url": section["citation_url"],
        "parent_section": (
            f"{section['parent_section_id']}: {section['parent_title']}"
            if section.get("parent_title")
            else ""
        ),
        "knowledge_url": section.get("knowledge_url", ""),
    }
    if score is not None:
        result = {"score": round(score, 2), **result}
    return result


