def read_policy_concept(concept_id: str, caller_id: str = "EMP-1001") -> dict[str, Any]:
    """Read the full verbatim text of a specific policy section or concept ID.

    Args:
        concept_id: Section identifier (e.g., "Section 5.4", "25.3", "1.2", "childcare",
                    "host gift") or topic keyword.
        caller_id: Employee ID of the caller (default: EMP-1001).

    Returns:
        Dictionary containing the verbatim policy section text and mandatory citation metadata.
    """
    log_audit_event(
        actor_id=caller_id,
        target_employee_id=caller_id,
        tool_name="read_policy_concept",
        target_system="PolicyKnowledgeBase",
        action_type="READ",
        decision="ALLOW",
        request_summary={"concept_id": concept_id},
    )
    sections = _get_sections()
    raw = (concept_id or "").strip()
    query_norm = re.sub(r"^section\s*", "", raw, flags=re.IGNORECASE).strip().lower()
    query_norm = query_norm.strip(".:# ")

    matched: list[dict[str, Any]] = []
    seen: set[str] = set()

    def push(sec: dict[str, Any]) -> None:
        if sec["section_id"] in seen:
            return
        seen.add(sec["section_id"])
        matched.append(_as_result(sec))

    # 1. Exact section number ("5.4").
    for s in sections:
        if query_norm == s["number"] or query_norm == s["section_id"].lower():
            push(s)

    # 2. Whole parent section ("5" -> 5.1 .. 5.5).
    if not matched and re.fullmatch(r"\d+", query_norm):
        for s in sorted(
            (x for x in sections if x["parent_number"] == query_norm),
            key=_section_sort_key,
        ):
            push(s)

    # 3. Title / parent-title substring.
    if not matched and query_norm:
        for s in sections:
            if query_norm in s["title"].lower() or query_norm in s["parent_title"].lower():
                push(s)

    # 4. Generated knowledge/ file lookup (`knowledge/section-5.4.md`).
    if not matched and KNOWLEDGE_DIR.exists() and query_norm:
        for md_file in sorted(KNOWLEDGE_DIR.rglob("*.md")):
            if md_file.name in ("log.md", "index.md"):
                continue
            if query_norm in md_file.stem.lower() or query_norm in md_file.parent.name.lower():
                file_text = md_file.read_text(encoding="utf-8")
                key = md_file.stem
                if key in seen:
                    continue
                seen.add(key)
                matched.append(
                    {
                        "section_id": md_file.stem.replace("section-", "Section "),
                        "title": md_file.stem,
                        "content": file_text[:_MAX_CONTENT_CHARS],
                        "citation_url": f"file://{md_file.resolve()}",
                        "parent_section": "",
                        "knowledge_url": f"file://{md_file.resolve()}",
                    }
                )

    # 5. Fall back to keyword search so topic words still resolve.
    if not matched and query_norm:
        terms = _build_query_terms(raw)
        scored = [
            (score, s)
            for s in sections
            if (score := _score_section(s, terms, raw)) >= _SCORE_THRESHOLD
        ]
        scored.sort(key=lambda x: (-x[0], _section_sort_key(x[1])))
        for _score, s in scored[:_MAX_RESULTS]:
            push(s)

    if not matched:
        return {
            "status": "NOT_FOUND",
            "message": (
                f"No policy concept matching '{concept_id}' was found in "
                "elevate-apac-m3-policydoc.md."
            ),
        }

    return {
        "status": "SUCCESS",
        "matches": matched[:_MAX_RESULTS],
        "citation_instruction": "Always cite the exact Section ID (e.g. Section X.Y) in your response.",
    }


def search_policy(query: str, caller_id: str = "EMP-1001") -> dict[str, Any]:
    """Search the official Altostrat Singapore Employee Policy Handbook (`elevate-apac-m3-policydoc.md`) by keywords or natural language question.

    Use this tool FIRST for any HR/IT policy question (leave rules, expense limits, gifts,
    work from home equipment allowance, relocation allowance, ITSM ticket lifecycle and
    priority rules, romantic relationships, childcare cap, TOIL, sick leave certificates, etc.).
    Japanese questions are supported and are expanded to the English handbook vocabulary.

    Args:
        query: Search keywords or question (e.g., "home office equipment allowance",
               "relocation allowance cap", "ticket lifecycle New Closed", "TOIL",
               "有給休暇は何日ですか").
        caller_id: Employee ID of the user running the search (default: EMP-1001).

    Returns:
        Top matching policy sections with verbatim text and exact `Section X.Y` citations.
    """
    log_audit_event(
        actor_id=caller_id,
        target_employee_id=caller_id,
        tool_name="search_policy",
        target_system="PolicyKnowledgeBase",
        action_type="READ",
        decision="ALLOW",
        request_summary={"query": query},
    )

    sections = _get_sections()
    terms = _build_query_terms(query or "")

    scored: list[tuple[float, dict[str, Any]]] = []
    if terms:
        for s in sections:
            score = _score_section(s, terms, query or "")
            if score >= _SCORE_THRESHOLD:
                scored.append((score, s))

    # Deterministic ordering: score desc, then document order.
    scored.sort(key=lambda x: (-x[0], _section_sort_key(x[1])))

    top_results = [_as_result(s, score) for score, s in scored[:_MAX_RESULTS]]

    if not top_results:
        return {
            "status": "NO_MATCH",
            "query": query,
            "message": (
                "No matching policy section found in elevate-apac-m3-policydoc.md. "
                "Per Grounding Enforcement (UC-1.1), do NOT guess or extrapolate unstated benefits."
            ),
        }

    return {
        "status": "SUCCESS",
        "query": query,
        "results": top_results,
        "grounding_notice": (
            "MANDATORY: Base your answer strictly on the verbatim 'content' returned above "
            "and cite the specific Section ID (e.g., Section 5.4, Section 25.3). If a benefit "
            "or allowance is not explicitly stated in the text, state that it is not provided in the policy."
        ),
    }
