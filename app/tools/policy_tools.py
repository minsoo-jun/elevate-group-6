# ---------------------------------------------------------------------------
# Text normalisation
# ---------------------------------------------------------------------------

#: Markdown escapes used throughout the handbook (e.g. `'3 \- Moderate'`,
#: `T\&E`, `12\.`, `\>$10,000`).  Unescaping is safe: it never touches digits.
_ESCAPE_RE = re.compile(r"\\([\\`*_{}\[\]()#+\-.!>&$~|<'\"])")
_NBSP_RE = re.compile(r"(&nbsp;|\u00a0)")
_TRAILING_WS_RE = re.compile(r"[ \t]+$", re.MULTILINE)
_MULTI_BLANK_RE = re.compile(r"\n{3,}")


def normalize_policy_text(text: str) -> str:
    """Normalise handbook text for display/citation without altering figures.

    Removes markdown escape backslashes (``'4 \\- Low'`` -> ``'4 - Low'``),
    converts ``&nbsp;`` to a plain space, drops Markdown hard-break trailing
    spaces and collapses runs of blank lines.  Dollar amounts, dates and
    percentages are preserved verbatim.
    """
    if not text:
        return ""
    out = text.replace("\r\n", "\n").replace("\r", "\n")
    out = _NBSP_RE.sub(" ", out)
    out = _ESCAPE_RE.sub(r"\1", out)
    out = _TRAILING_WS_RE.sub("", out)
    out = _MULTI_BLANK_RE.sub("\n\n", out)
    return out.strip()


def _searchable(text: str) -> str:
    """Lowercase, markup-stripped projection of `text` used for scoring."""
    out = normalize_policy_text(text).lower()
    out = out.replace("**", " ").replace("*", " ")
    out = out.replace("→", " -> ")
    out = re.sub(r"[ \t]+", " ", out)
    return out


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


# ---------------------------------------------------------------------------
# Handbook parser
# ---------------------------------------------------------------------------

#: `**SECTION 5: ETHICS, COMPLIANCE, & CONDUCT perimeters**`
_PARENT_RE = re.compile(r"^\*\*SECTION\s+(\d+)\s*:\s*(.+?)\*\*[ \t]*$", re.MULTILINE)

#: `**5.4 Remote Work, Telework, & Data Security**` optionally followed by body
#: text on the same line (`**7.1 General Commitment...** Altostrat has ...`).
_SUB_RE = re.compile(r"^\*\*(\d+\.\d+)\s+(.+?)\*\*[ \t]*(.*)$", re.MULTILINE)


def _clean_title(title: str) -> str:
    return normalize_policy_text(title).replace("**", "").strip().strip(":").strip()


def parse_policy_document(text: str | None = None) -> list[dict[str, Any]]:
    """Parse the handbook into `N.M` section chunks with parent-section context.

    Returns a list of dicts ordered by their position in the document. Each
    dict carries: ``section_id`` (``"Section 5.4"``), ``number`` (``"5.4"``),
    ``title``, ``parent_section_id``, ``parent_number``, ``parent_title``,
    ``content`` (normalised verbatim body, heading line included),
    ``line_start`` / ``line_end`` and ``citation_url``.
    """
    if text is None:
        if not POLICY_DOC_PATH.exists():
            return []
        text = POLICY_DOC_PATH.read_text(encoding="utf-8")
    text = text.replace("\r\n", "\n").replace("\r", "\n")

    # Offset -> 1-based line number helper.
    line_starts = [0]
    for m in re.finditer(r"\n", text):
        line_starts.append(m.end())

    def line_of(pos: int) -> int:
        lo, hi = 0, len(line_starts) - 1
        while lo < hi:
            mid = (lo + hi + 1) // 2
            if line_starts[mid] <= pos:
                lo = mid
            else:
                hi = mid - 1
        return lo + 1

    parents = [
        {
            "number": m.group(1),
            "title": _clean_title(m.group(2)),
            "start": m.start(),
            "end": m.end(),
        }
        for m in _PARENT_RE.finditer(text)
    ]
    subs = list(_SUB_RE.finditer(text))

    # Boundaries: a chunk ends at the next sub-section OR the next parent.
    boundaries = sorted(
        [p["start"] for p in parents] + [s.start() for s in subs] + [len(text)]
    )

    def next_boundary(pos: int) -> int:
        for b in boundaries:
            if b > pos:
                return b
        return len(text)

    def parent_for(pos: int) -> dict[str, Any] | None:
        current = None
        for p in parents:
            if p["start"] <= pos:
                current = p
            else:
                break
        return current

    sections: list[dict[str, Any]] = []
    used_ids: set[str] = set()
    parents_with_children: set[str] = set()

    def _add(record: dict[str, Any]) -> None:
        sec_id = record["section_id"]
        if sec_id in used_ids:  # the source doc reuses "SECTION 30" twice
            suffix = 2
            while f"{sec_id} ({suffix})" in used_ids:
                suffix += 1
            record["section_id"] = f"{sec_id} ({suffix})"
        used_ids.add(record["section_id"])
        sections.append(record)

    for match in subs:
        number = match.group(1)
        title = _clean_title(match.group(2))
        inline_body = match.group(3).strip()
        parent = parent_for(match.start())
        if parent is not None:
            parents_with_children.add(parent["number"] + "@" + str(parent["start"]))

        body_start = match.end()
        body_end = next_boundary(match.start())
        body = text[body_start:body_end]
        if inline_body:
            # Heading and body shared a line: keep only the heading in `title`
            # and push the remainder to the front of the body.  `match.end()`
            # already sits past the inline remainder, so just prepend it.
            body = inline_body + "\n\n" + body
        body = normalize_policy_text(body)

        parent_number = parent["number"] if parent else ""
        parent_title = parent["title"] if parent else ""
        heading = f"**{number} {title}**"
        content = f"{heading}\n\n{body}".strip() if body else heading

        line_start = line_of(match.start())
        line_end = max(line_start, line_of(max(body_end - 1, match.start())))
        _add(
            {
                "section_id": f"Section {number}",
                "number": number,
                "title": title,
                "parent_section_id": f"SECTION {parent_number}" if parent_number else "",
                "parent_number": parent_number,
                "parent_title": parent_title,
                "content": content,
                "line_start": line_start,
                "line_end": line_end,
                "citation_url": (
                    f"file://{POLICY_DOC_PATH}#L{line_start}-L{line_end}"
                ),
                "anchor": _slug(f"{number}-{title}"),
            }
        )

    # Parent sections that have no `N.M` children at all (e.g. "SECTION 30:
    # New Employee Onboarding Guidelines") would otherwise be unsearchable.
    for idx, parent in enumerate(parents):
        key = parent["number"] + "@" + str(parent["start"])
        if key in parents_with_children:
            continue
        start = parent["start"]
        end = parents[idx + 1]["start"] if idx + 1 < len(parents) else len(text)
        body = normalize_policy_text(text[parent["end"] : end])
        if not body:
            continue
        heading = f"**SECTION {parent['number']}: {parent['title']}**"
        line_start = line_of(start)
        line_end = max(line_start, line_of(max(end - 1, start)))
        record = {
            "section_id": f"Section {parent['number']}",
            "number": parent["number"],
            "title": parent["title"],
            "parent_section_id": f"SECTION {parent['number']}",
            "parent_number": parent["number"],
            "parent_title": parent["title"],
            "content": f"{heading}\n\n{body}".strip(),
            "line_start": line_start,
            "line_end": line_end,
            "citation_url": f"file://{POLICY_DOC_PATH}#L{line_start}-L{line_end}",
            "anchor": _slug(f"{parent['number']}-{parent['title']}"),
        }
        # keep document order
        insert_at = len(sections)
        for i, existing in enumerate(sections):
            if existing["line_start"] > line_start:
                insert_at = i
                break
        used_ids.add(record["section_id"])
        sections.insert(insert_at, record)

    for sec in sections:
        knowledge_file = KNOWLEDGE_DIR / KNOWLEDGE_FILE_TEMPLATE.format(
            number=sec["number"]
        )
        sec["knowledge_url"] = f"file://{knowledge_file}"
        sec["_haystack_title"] = _searchable(f"{sec['title']} {sec['parent_title']}")
        sec["_haystack_body"] = _searchable(sec["content"])
    return sections


def _load_policy_sections() -> list[dict[str, Any]]:
    """Backwards-compatible alias retained for existing callers/tests."""
    return parse_policy_document()


_CACHED_SECTIONS: list[dict[str, Any]] | None = None
_CACHED_MTIME: float | None = None


def _get_sections() -> list[dict[str, Any]]:
    global _CACHED_SECTIONS, _CACHED_MTIME
    try:
        mtime = POLICY_DOC_PATH.stat().st_mtime
    except OSError:
        mtime = None
    if _CACHED_SECTIONS is None or mtime != _CACHED_MTIME:
        _CACHED_SECTIONS = _load_policy_sections()
        _CACHED_MTIME = mtime
    return _CACHED_SECTIONS


