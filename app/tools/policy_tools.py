"""Policy Knowledge Base Retrieval Tools (SDD §3.2, §3.3, UC-1.1).

Provides deterministic, grounded retrieval over `elevate-apac-m3-policydoc.md`
and `knowledge/` markdown files with section-level citations (`Section X.Y`).

Document format (official customer-provided handbook, 1,176 lines)
------------------------------------------------------------------
The handbook does NOT use ATX markdown headings (`# N.M Title`). Instead it
uses bold-text headings::

    **SECTION 5: ETHICS, COMPLIANCE, & CONDUCT perimeters**

    **5.4 Remote Work, Telework, & Data Security**

    * **Home Office Equipment Allowance:** ... $500 USD ...

Some sub-section headings are followed by body text *on the same line*::

    **7.1 General Commitment and Applicability** Altostrat has an unwavering...

The parser below handles both shapes, keeps the parent `SECTION N` title on
every `N.M` chunk, and normalises markdown escaping (`\\-`, `&nbsp;`, trailing
double-spaces) without mangling figures such as `$500 USD` or `'4 - Low'`.

Public API (stable - consumed by `app/agent.py` and `ui/server.py`):
    - search_policy(query, caller_id)
    - list_policy_concepts(caller_id)
    - read_policy_concept(concept_id, caller_id)
"""
